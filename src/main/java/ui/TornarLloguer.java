    private void posarTextos() {
        setTitle(bundle.getString("titol.tornarLloguer"));

        lblJoc.setText(bundle.getString("etiqueta.joc"));
        lblUsuari.setText(bundle.getString("etiqueta.usuari"));
        lblPlataforma.setText(bundle.getString("etiqueta.plataforma"));
        lblDataInici.setText(bundle.getString("etiqueta.dataInici"));

        btnMarcarRetornat.setText(bundle.getString("boto.marcarRetornat"));
        btnTancar.setText(bundle.getString("boto.tancar"));
    }
    
    private void configurarTaula() {
        String[] columnes = {
            bundle.getString("taula.numRegistre"),
            bundle.getString("taula.joc"),
            bundle.getString("taula.usuari"),
            bundle.getString("taula.plataforma"),
            bundle.getString("taula.dataInici")
        };

        modelTaula = new DefaultTableModel(columnes, 0) {
            @Override
            public boolean isCellEditable(int fila, int columna) {
                return false;
            }
        };
        taulaActius.setModel(modelTaula);
        taulaActius.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
    }
    
    private void carregarTaula() {
        actius = gestor.getLloguersActius();
        modelTaula.setRowCount(0);

        for (Lloguer l : actius) {
            Object[] fila = {
                String.format("%02d", l.getNumRegistre()),
                l.getJoc().getTitol(),
                l.getUsuari().getNomComplet(),
                l.getPlataforma().getNom(),
                l.getDataInici().format(format)
            };
            modelTaula.addRow(fila);
        }
    }
    
    private void mostrarDetall() {
        int fila = taulaActius.getSelectedRow();

        if (fila == -1) {
            lblValJoc.setText("");
            lblValUsuari.setText("");
            lblValPlataforma.setText("");
            lblValDataInici.setText("");
            btnMarcarRetornat.setEnabled(false); // sin selección no se puede devolver
        } else {
            Lloguer l = actius.get(fila);
            lblValJoc.setText(l.getJoc().getTitol());
            lblValUsuari.setText(l.getUsuari().getNomComplet());
            lblValPlataforma.setText(l.getPlataforma().getNom());
            lblValDataInici.setText(l.getDataInici().format(format));
            btnMarcarRetornat.setEnabled(true);
        }
    }
    
