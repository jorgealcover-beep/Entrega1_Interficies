    private void btnMarcarRetornatActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMarcarRetornatActionPerformed
       int fila = taulaActius.getSelectedRow();

    if (fila == -1) {
        JOptionPane.showMessageDialog(this, bundle.getString("error.senseSeleccio"),
                bundle.getString("error.titol"), JOptionPane.ERROR_MESSAGE);
        return;
    }

    Lloguer lloguer = actius.get(fila);

    try {
        gestor.tornarLloguer(lloguer);   
        JOptionPane.showMessageDialog(this, bundle.getString("info.lloguerRetornat"),
                bundle.getString("info.titol"), JOptionPane.INFORMATION_MESSAGE);
        carregarTaula();   
        mostrarDetall();   
    } catch (GestorException e) {
        JOptionPane.showMessageDialog(this, e.getMessage(),
                bundle.getString("error.titol"), JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnMarcarRetornatActionPerformed

