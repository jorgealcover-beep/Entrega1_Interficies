    public RegistrarLloguer(java.awt.Frame parent, boolean modal, GestorDades gestor,
        Usuari usuariInicial, Joc jocInicial) {
        super(parent, modal);
        initComponents();
        this.gestor = gestor;

        radios = new JRadioButton[]{jRadioButtonPS5, jRadioButtonSwitch, jRadioButtonXbox, jRadioButtonPC};

        posarTextos();
        carregarCombos();

        // Si venimos de la ventana principal con una fila seleccionada
        if (usuariInicial != null) {
            jComboBoxUsuari.setSelectedItem(usuariInicial);
        }
        if (jocInicial != null) {
            jComboBoxJoc.setSelectedItem(jocInicial);
        }

        // Número y fechas automáticas, que el usuario no puede modificar
        txtNumRegistre.setText(String.format("%02d", gestor.getProperNumRegistre()));
        txtDataInici.setText(LocalDate.now().format(format));
        txtDataTornada.setText(LocalDate.now().plusDays(Lloguer.DIES_LLOGUER).format(format));
        txtNumRegistre.setEditable(false);
        txtDataInici.setEnabled(false);
        txtDataTornada.setEnabled(false);

        actualitzarPlataformes();
        setLocationRelativeTo(parent);
}
    
    private void carregarCombos() {
        DefaultComboBoxModel<Usuari> modelUsuaris = new DefaultComboBoxModel<>();
        for (Usuari u : gestor.getUsuaris()) {
            modelUsuaris.addElement(u);
        }
        jComboBoxUsuari.setModel(modelUsuaris);

        DefaultComboBoxModel<Joc> modelJocs = new DefaultComboBoxModel<>();
        for (Joc j : gestor.getJocs()) {
            modelJocs.addElement(j);
        }
        jComboBoxJoc.setModel(modelJocs);
    }
