    private String textUnitats(int unitats) {
        if (unitats == 1) {
            return unitats + " " + bundle.getString("plat.unitat");
        }
        return unitats + " " + bundle.getString("plat.unitats");
}
    private void actualitzarPlataformes() {
        if (gestor == null) {
            return; // todavía no está listo el diálogo
        }

        Joc joc = (Joc) jComboBoxJoc.getSelectedItem();
        buttonGroupPlataforma.clearSelection(); 

        Plataforma[] plataformes = Plataforma.values();
        for (int i = 0; i < plataformes.length; i++) {
            int unitats = 0;
            if (joc != null) {
                unitats = joc.getUnitatsDisponibles(plataformes[i]);
            }
            radios[i].setText(plataformes[i].getNom() + "   (" + textUnitats(unitats) + ")");
            radios[i].setEnabled(unitats > 0); // sin stock = deshabilitado
        }

        // Panel "Informació del joc"
        if (joc != null) {
            lblValGenere.setText(joc.getGenere());
            lblValPS5.setText(String.valueOf(joc.getUnitatsDisponibles(Plataforma.PS5)));
            lblValSwitch2.setText(String.valueOf(joc.getUnitatsDisponibles(Plataforma.SWITCH2)));
            lblValXbox.setText(String.valueOf(joc.getUnitatsDisponibles(Plataforma.XBOX)));
            lblValPC.setText(String.valueOf(joc.getUnitatsDisponibles(Plataforma.PC)));
        } else {
            lblValGenere.setText("");
            lblValPS5.setText("0");
            lblValSwitch2.setText("0");
            lblValXbox.setText("0");
            lblValPC.setText("0");
        }
}
