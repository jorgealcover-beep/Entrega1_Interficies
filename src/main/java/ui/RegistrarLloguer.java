    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        Usuari usuari = (Usuari) jComboBoxUsuari.getSelectedItem();
        Joc joc = (Joc) jComboBoxJoc.getSelectedItem();

        // Buscamos qué radio button está marcado
        Plataforma plataforma = null;
        Plataforma[] plataformes = Plataforma.values();
        for (int i = 0; i < radios.length; i++) {
            if (radios[i].isSelected()) {
                plataforma = plataformes[i];
            }
        }

        if (plataforma == null) {
            JOptionPane.showMessageDialog(this, bundle.getString("error.plataforma"),
                    bundle.getString("error.titol"), JOptionPane.ERROR_MESSAGE);
            return;
        }

        try {
            gestor.registrarLloguer(usuari, joc, plataforma);
            JOptionPane.showMessageDialog(this, bundle.getString("info.lloguerRegistrat"),
                    bundle.getString("info.titol"), JOptionPane.INFORMATION_MESSAGE);
            dispose(); // cierra el diálogo
        } catch (GestorException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(),
                    bundle.getString("error.titol"), JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

