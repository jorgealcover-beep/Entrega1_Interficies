    private void jMenuItemRegistrarLloguerActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItemRegistrarLloguerActionPerformed
    Usuari usuariTriat = null;
    Joc jocTriat = null;

    int fila = jTablePrincipal.getSelectedRow();
    if (fila != -1) {
        // La fila de la tabla coincide con la posición en la lista del gestor
        Lloguer seleccionat = gestor.getLloguers().get(fila);
        usuariTriat = seleccionat.getUsuari();
        jocTriat = seleccionat.getJoc();
    }

    RegistrarLloguer finestra = new RegistrarLloguer(this, true, gestor, usuariTriat, jocTriat);
    finestra.setVisible(true);

    // El diálogo es modal: esta línea no se ejecuta hasta que se cierre
    actualitzarTaula();
    }//GEN-LAST:event_jMenuItemRegistrarLloguerActionPerformed

