    private void configurarTaula() {
    String[] columnes = {
        bundle.getString("taula.numRegistre"),
        bundle.getString("taula.joc"),
        bundle.getString("taula.usuari"),
        bundle.getString("taula.plataforma"),
        bundle.getString("taula.dataInici"),
        bundle.getString("taula.dataTornada"),
        bundle.getString("taula.genere"),
        bundle.getString("taula.estat")
    };
    modelTaula = new DefaultTableModel(columnes, 0) {
        @Override
        public boolean isCellEditable(int fila, int columna) {
            return false;
        }
    };
    jTablePrincipal.setModel(modelTaula);
    jTablePrincipal.setDefaultRenderer(Object.class, new RenderColors());
}
    public void actualitzarTaula() {
    modelTaula.setRowCount(0);

    for (Lloguer l : gestor.getLloguers()) {
        Object[] fila = {
            String.format("%02d", l.getNumRegistre()),
            l.getJoc().getTitol(),
            l.getUsuari().getNomComplet(),
            l.getPlataforma().getNom(),
            l.getDataInici().format(format),
            l.getDataPrevista().format(format),
            l.getJoc().getGenere(),
            l.getEstat().toString()
        };
        modelTaula.addRow(fila);
    }

    lblTotal.setText(bundle.getString("etiqueta.totalLloguers") + " " + gestor.getTotalLloguers());
}
    private class RenderColors extends DefaultTableCellRenderer {
    @Override
    public Component getTableCellRendererComponent(JTable taula, Object valor,
            boolean seleccionada, boolean focus, int fila, int columna) {

        Component c = super.getTableCellRendererComponent(taula, valor, seleccionada, focus, fila, columna);

        // La fila 0 de la tabla es el primer lloguer de la lista del gestor
        Lloguer l = gestor.getLloguers().get(fila);

        if (!seleccionada) {
            if (l.getEstat() == Lloguer.Estat.RETORNAT) {
                c.setBackground(new Color(180, 240, 180));      // verde
            } else if (l.getEstat() == Lloguer.Estat.FORA_DE_TERMINI) {
                c.setBackground(new Color(250, 170, 170));      // rojo
            } else {
                c.setBackground(Color.WHITE);
            }
        }
        return c;
    }
}
