    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        String nom = txtNom.getText().trim();
        String llinatge1 = txtLlinatge1.getText().trim();
        String llinatge2 = txtLlinatge2.getText().trim();
        String dni = txtDni.getText().trim();
        String telefon = txtTelefon.getText().trim();


        if (ValidationAPI.campBuit(nom) || ValidationAPI.campBuit(llinatge1)
                || ValidationAPI.campBuit(llinatge2) || ValidationAPI.campBuit(dni)
                || ValidationAPI.campBuit(telefon)) {
            mostrarError(bundle.getString("error.campBuit"));
            return;
        }

        if (!ValidationAPI.nomValid(nom)) {
            mostrarError(bundle.getString("error.nomMajuscula"));
            txtNom.requestFocus();
            return;
        }
        if (!ValidationAPI.nomValid(llinatge1) || !ValidationAPI.nomValid(llinatge2)) {
            mostrarError(bundle.getString("error.llinatgeMajuscula"));
            return;
        }


        if (!ValidationAPI.dniValid(dni)) {
            mostrarError(bundle.getString("error.dni"));
            txtDni.requestFocus();
            return;
        }
        if (!ValidationAPI.telefonValid(telefon)) {
            mostrarError(bundle.getString("error.telefon"));
            txtTelefon.requestFocus();
            return;
        }


        try {
            Usuari nou = new Usuari(nom, llinatge1, llinatge2, dni, telefon);
            gestor.crearUsuari(nou);
            JOptionPane.showMessageDialog(this, bundle.getString("info.usuariCreat"),
                    bundle.getString("info.titol"), JOptionPane.INFORMATION_MESSAGE);
            dispose();
        } catch (GestorException e) {

            mostrarError(e.getMessage());
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

