    private void btnConfirmarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmarActionPerformed
        String titol = txtNom.getText().trim();
        String genere = (String) cmbGenere.getSelectedItem();


        if (ValidationAPI.campBuit(titol)) {
            mostrarError(bundle.getString("error.campBuit"));
            return;
        }


        if (!ValidationAPI.nomValid(titol)) {
            mostrarError(bundle.getString("error.titolMajuscula"));
            txtNom.requestFocus();
            return;
        }


        HashMap<Plataforma, Integer> unitats = new HashMap<>();
        Plataforma[] plataformes = Plataforma.values();
        for (int i = 0; i < checks.length; i++) {
            if (checks[i].isSelected()) {
                int quantitat = (int) spinners[i].getValue();
                if (quantitat > 0) {
                    unitats.put(plataformes[i], quantitat);
                }
            }
        }


        if (unitats.isEmpty()) {
            mostrarError(bundle.getString("error.plataformes"));
            return;
        }


        try {
            Joc nou = new Joc(titol, genere, unitats);
            gestor.crearJoc(nou);
            JOptionPane.showMessageDialog(this, bundle.getString("info.jocCreat"),
                    bundle.getString("info.titol"), JOptionPane.INFORMATION_MESSAGE);
            dispose();
        } catch (GestorException e) {
            mostrarError(e.getMessage());
        }
    }//GEN-LAST:event_btnConfirmarActionPerformed

