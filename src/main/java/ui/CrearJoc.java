    private void posarTextos() {
        setTitle(bundle.getString("titol.crearJoc"));

        lblNom.setText(bundle.getString("etiqueta.nom") + " *:");
        lblGenere.setText(bundle.getString("etiqueta.genere") + " *:");

        panelPlataformes.setBorder(javax.swing.BorderFactory.createTitledBorder(
                bundle.getString("panell.plataformesDisponibles")));

        
        Plataforma[] plataformes = Plataforma.values();
        for (int i = 0; i < checks.length; i++) {
            checks[i].setText(plataformes[i].getNom());
        }

        lblUnitats1.setText(bundle.getString("etiqueta.unitats"));
        lblUnitats2.setText(bundle.getString("etiqueta.unitats"));
        lblUnitats3.setText(bundle.getString("etiqueta.unitats"));
        lblUnitats4.setText(bundle.getString("etiqueta.unitats"));

        btnConfirmar.setText(bundle.getString("boto.confirmar"));
        btnCancellar.setText(bundle.getString("boto.cancellar"));
    }
    
    private void configurarGeneres() {
        String[] generes = {"Acció", "Aventura", "Esports", "Estratègia", "Simulació", "Terror"};
        cmbGenere.setModel(new DefaultComboBoxModel<>(generes));
    }
    
    private void configurarSpinners() {
        for (int i = 0; i < spinners.length; i++) {
            spinners[i].setModel(new SpinnerNumberModel(0, 0, 99, 1));
        }
    }
    
    private void actualitzarSpinners() {
        for (int i = 0; i < checks.length; i++) {
            if (checks[i].isSelected()) {
                spinners[i].setEnabled(true);
                // Si estaba a 0, lo ponemos a 1 para que sea un valor válido
                if ((int) spinners[i].getValue() == 0) {
                    spinners[i].setValue(1);
                }
            } else {
                spinners[i].setEnabled(false);
                spinners[i].setValue(0);
            }
        }
    }
    
    private void mostrarError(String missatge) {
        JOptionPane.showMessageDialog(this, missatge, bundle.getString("error.titol"), JOptionPane.ERROR_MESSAGE);
    }
